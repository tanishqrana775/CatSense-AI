"""
Comprehensive Verification Test for:
1. Security Headers (X-Content-Type-Options, X-Frame-Options, Referrer-Policy, X-XSS-Protection)
2. Werkzeug Password Hashing (generate_password_hash / check_password_hash)
3. Custom 404 Error Handler & Template
4. Custom 500 Error Handler & Template
"""
import sys
from pathlib import Path
from werkzeug.security import check_password_hash

PROJECT_ROOT = Path(__file__).resolve().parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from app import app
from database.database_logic import db, User

# Register test 500 route at module level before any requests are handled
@app.route("/test_trigger_500_error")
def trigger_500():
    raise RuntimeError("Simulated internal server exception for 500 test")

def test_security_and_templates():
    print("=" * 70)
    print("VERIFYING SECURITY HEADERS, WERKZEUG PASSWORDS, & ERROR TEMPLATES")
    print("=" * 70)

    app.config["TESTING"] = True
    app.config["WTF_CSRF_ENABLED"] = False

    with app.test_client() as client:
        # -------------------------------------------------------------
        # 1. Security Headers Verification
        # -------------------------------------------------------------
        print("\n--- 1. Security Headers via after_request Check ---")
        res = client.get("/")
        headers = res.headers

        print(f"X-Content-Type-Options: {headers.get('X-Content-Type-Options')}")
        print(f"X-Frame-Options: {headers.get('X-Frame-Options')}")
        print(f"Referrer-Policy: {headers.get('Referrer-Policy')}")
        print(f"X-XSS-Protection: {headers.get('X-XSS-Protection')}")

        assert headers.get("X-Content-Type-Options") == "nosniff", "Missing or incorrect X-Content-Type-Options"
        assert headers.get("X-Frame-Options") == "DENY", "Missing or incorrect X-Frame-Options"
        assert headers.get("Referrer-Policy") == "strict-origin-when-cross-origin", "Missing or incorrect Referrer-Policy"
        assert headers.get("X-XSS-Protection") == "1; mode=block", "Missing or incorrect X-XSS-Protection"
        print("✅ Security headers verified on response.")

        # -------------------------------------------------------------
        # 2. Werkzeug Password Hashing Verification
        # -------------------------------------------------------------
        print("\n--- 2. Werkzeug Password Hashing Check ---")
        test_email = "werkzeug_test_cat@example.com"
        test_password = "SuperCatSecretPass999!"

        # Remove test user if previously existed
        with app.app_context():
            existing = User.query.filter_by(email=test_email).first()
            if existing:
                db.session.delete(existing)
                db.session.commit()

        # Register new user through Flask endpoint
        reg_res = client.post("/register", data={
            "full_name": "Werkzeug Cat",
            "email": test_email,
            "password": test_password,
            "confirm_password": test_password
        }, follow_redirects=True)
        assert reg_res.status_code == 200

        with app.app_context():
            created_user = User.query.filter_by(email=test_email).first()
            assert created_user is not None, "User was not created!"
            hash_val = created_user.password_hash
            print(f"Saved password_hash: {hash_val[:35]}... (length={len(hash_val)})")
            
            # Confirm hash is generated by werkzeug (standard scrypt or pbkdf2 prefix)
            assert hash_val.startswith("scrypt:") or hash_val.startswith("pbkdf2:"), (
                f"Password hash does not have werkzeug prefix: {hash_val}"
            )
            # Confirm check_password_hash validates correctly
            assert check_password_hash(hash_val, test_password), "check_password_hash failed with correct password!"
            assert not check_password_hash(hash_val, "WrongPassword"), "check_password_hash succeeded with wrong password!"
            assert created_user.check_password(test_password), "User.check_password() helper failed!"

        # Test login via Flask endpoint
        login_res = client.post("/login", data={
            "email": test_email,
            "password": test_password
        }, follow_redirects=True)
        assert login_res.status_code == 200
        html = login_res.data.decode("utf-8")
        assert "Welcome back" in html or "Dashboard" in html
        print("✅ Werkzeug generate_password_hash & check_password_hash verified end-to-end.")

        # -------------------------------------------------------------
        # 3. Custom 404 Error Handler & Template Verification
        # -------------------------------------------------------------
        print("\n--- 3. Custom 404 Error Handler Check ---")
        res_404 = client.get("/this_route_definitely_does_not_exist_404")
        print(f"Status Code: {res_404.status_code}")
        html_404 = res_404.data.decode("utf-8")
        
        assert res_404.status_code == 404, f"Expected 404 status code, got {res_404.status_code}"
        assert "Lost in the Scratching Post?" in html_404, "Custom 404 message not found in template!"
        assert "404" in html_404, "404 badge not found in template!"
        assert res_404.headers.get("X-Frame-Options") == "DENY", "Security headers not applied to 404 response!"
        print("✅ Custom 404 handler and template verified.")

        # -------------------------------------------------------------
        # 4. Custom 500 Error Handler & Template Verification
        # -------------------------------------------------------------
        print("\n--- 4. Custom 500 Error Handler Check ---")
        # In testing mode, Flask propagates exceptions unless app.config['TESTING'] = False
        app.config["TESTING"] = False
        res_500 = client.get("/test_trigger_500_error")
        app.config["TESTING"] = True

        print(f"Status Code: {res_500.status_code}")
        html_500 = res_500.data.decode("utf-8")
        
        assert res_500.status_code == 500, f"Expected 500 status code, got {res_500.status_code}"
        assert "Cat-astrophe" in html_500, "Custom 500 message not found in template!"
        assert "500" in html_500, "500 badge not found in template!"
        assert res_500.headers.get("X-Frame-Options") == "DENY", "Security headers not applied to 500 response!"
        print("✅ Custom 500 handler and template verified.")

    print("\n" + "=" * 70)
    print("ALL SECURITY HEADERS, PASSWORD, AND TEMPLATE TESTS PASSED!")
    print("=" * 70)

if __name__ == "__main__":
    test_security_and_templates()
